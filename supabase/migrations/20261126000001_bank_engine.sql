-- Generalise the on-tap-11 question bank so the TOEIC and IELTS courses use the
-- same engine. The ot_ prefix stays (renaming every table and function would
-- buy nothing); read it as "question bank".
--
-- What this adds:
--   * every bank row belongs to a course; access checks use that course
--   * shared passages / listening scripts (ot_stimuli) for TOEIC Part 3/4/6/7
--     and IELTS, and tags for practising one grammar point or question type
--   * a "mock" pool: mock test questions never appear in practice and stay
--     invisible until the learner sits that test
--   * timed mock tests with score conversion, written to mock_scores on submit
--   * service-role-only functions the content importer uses to upsert sets
--
-- on-tap-11 rows keep the ids from the old SQLite file. Rows created by the
-- importer get identity ids (from 1,000,000) and are matched by ext_id.

