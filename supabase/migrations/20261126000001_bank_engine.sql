create or replace function public.ot_start_exam(p_topic_ids int[], p_count int, p_minutes int, p_types text[])
returns bigint
language plpgsql security definer set search_path = '' as $$
declare
  v_count int := least(greatest(coalesce(p_count, 20), 1), 100);
  v_minutes int := least(greatest(coalesce(p_minutes, 30), 0), 240);
  v_types text[] := coalesce(nullif(p_types, '{}'), array['mcq']);
  v_courses text[];
  v_attempt bigint;
begin
  select array_agg(distinct public.ot_topic_course(t)) into v_courses from unnest(p_topic_ids) t;
  if coalesce(array_length(v_courses, 1), 0) <> 1 then
    raise exception 'pick topics from one course' using errcode = '22023';
  end if;
  perform public.ot_require_course(v_courses[1]);

  insert into public.ot_attempts (user_id, course_id, mode, config, deadline_at)
  values (
    auth.uid(), v_courses[1], 'exam',
    jsonb_build_object('topic_ids', p_topic_ids, 'count', v_count, 'minutes', v_minutes, 'types', v_types),
    case when v_minutes > 0 then now() + make_interval(mins => v_minutes) end
  )
  returning id into v_attempt;

  insert into public.ot_attempt_answers (attempt_id, question_id, sort)
  select v_attempt, x.id, (row_number() over ())::int - 1
    from (
      select q.id from public.ot_questions q
       where q.status = 'ok' and q.pool = 'practice' and q.topic_id = any (p_topic_ids) and q.type = any (v_types)
       order by random() limit v_count
    ) x;

  if not exists (select 1 from public.ot_attempt_answers where attempt_id = v_attempt) then
    delete from public.ot_attempts where id = v_attempt;
    raise exception 'no questions match the selected topics' using errcode = 'P0002';
  end if;
  return v_attempt;
end;
$$;

-- Start a published mock test: fixed questions in a fixed order, timed.
create function public.ot_start_mock(p_test text) returns bigint
language plpgsql security definer set search_path = '' as $$
declare
  t record;
  v_attempt bigint;
begin
  select * into t from public.ot_mock_tests where id = p_test and (published or public.is_admin());
  if not found then
    raise exception 'mock test % not found', p_test using errcode = 'P0002';
  end if;
  perform public.ot_require_course(t.course_id);

  insert into public.ot_attempts (user_id, course_id, mode, mock_test_id, config, deadline_at)
  values (auth.uid(), t.course_id, 'mock', t.id, jsonb_build_object('test_id', t.id, 'minutes', t.minutes),
          now() + make_interval(mins => t.minutes))
  returning id into v_attempt;

  insert into public.ot_attempt_answers (attempt_id, question_id, sort)
  select v_attempt, mq.question_id, mq.sort
    from public.ot_mock_questions mq join public.ot_questions q on q.id = mq.question_id
   where mq.test_id = t.id and q.status = 'ok';

  if not exists (select 1 from public.ot_attempt_answers where attempt_id = v_attempt) then
    delete from public.ot_attempts where id = v_attempt;
    raise exception 'mock test % has no questions', p_test using errcode = 'P0002';
  end if;
  return v_attempt;
end;
$$;

-- Convert a graded mock attempt to section scores and record it in mock_scores.
-- TOEIC totals add up; IELTS overall is the mean band rounded the IELTS way.
create function public.ot_record_mock_score(p_attempt bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  a record;
  t record;
  sec jsonb;
  v_key text;
  v_raw int;
  v_max int;
  v_scaled numeric;
  v_result jsonb := '{}';
  v_sum numeric := 0;
  v_n int := 0;
  v_total numeric;
begin
  select * into a from public.ot_attempts where id = p_attempt;
  select * into t from public.ot_mock_tests where id = a.mock_test_id;
  if not found then
    return null;
  end if;

  for sec in select value from jsonb_array_elements(t.sections) loop
    v_key := sec ->> 'key';
    select count(*) filter (where aa.is_correct), count(*)
      into v_raw, v_max
      from public.ot_attempt_answers aa
      join public.ot_mock_questions mq on mq.test_id = t.id and mq.question_id = aa.question_id
     where aa.attempt_id = p_attempt and mq.section = v_key;
    select (e ->> 1)::numeric into v_scaled
      from jsonb_array_elements(sec -> 'scale') e
     where (e ->> 0)::int <= v_raw
     order by (e ->> 0)::int desc
     limit 1;
    v_scaled := coalesce(v_scaled, 0);
    v_result := v_result || jsonb_build_object(
      v_key, jsonb_build_object('label', sec ->> 'label', 'raw', v_raw, 'max', v_max, 'scaled', v_scaled)
    );
    v_sum := v_sum + v_scaled;
    v_n := v_n + 1;
  end loop;

  v_total := case
    when a.course_id = 'ielts' then floor(v_sum / greatest(v_n, 1) * 2 + 0.5) / 2
    else v_sum
  end;

  insert into public.mock_scores (user_id, course_id, week, listening, reading, writing, speaking, total)
  values (
    a.user_id, a.course_id, t.week,
    (v_result -> 'listening' ->> 'scaled')::numeric,
    (v_result -> 'reading' ->> 'scaled')::numeric,
    (v_result -> 'writing' ->> 'scaled')::numeric,
    (v_result -> 'speaking' ->> 'scaled')::numeric,
    v_total
  );
  update public.ot_attempts
     set config = coalesce(config, '{}') || jsonb_build_object('sections', v_result, 'total', v_total)
   where id = p_attempt;
  return jsonb_build_object('sections', v_result, 'total', v_total);
end;
$$;

create or replace function public.ot_submit_exam(p_attempt bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  r record;
  g record;
  v_total int := 0;
  v_max int := 0;
  v_submitted timestamptz;
  v_mode text;
begin
  select submitted_at, mode into v_submitted, v_mode
    from public.ot_attempts where id = p_attempt and user_id = auth.uid() for update;
  if not found then
    raise exception 'attempt not found' using errcode = 'P0002';
  end if;
  if v_submitted is null then
    for r in
      select aa.question_id, aa.response, q.type, k.answer_key
        from public.ot_attempt_answers aa
        join public.ot_questions q on q.id = aa.question_id
        left join public.ot_question_keys k on k.question_id = aa.question_id
       where aa.attempt_id = p_attempt
       order by aa.sort
    loop
      select * into g from public.ot_grade(r.type, r.answer_key, r.response);
      update public.ot_attempt_answers set is_correct = g.is_correct, score = g.score
       where attempt_id = p_attempt and question_id = r.question_id;
      if g.score is not null then
        v_total := v_total + g.score;
        v_max := v_max + 100;
      end if;
      perform public.ot_bump_stats(auth.uid(), r.question_id, g.is_correct);
    end loop;
    update public.ot_attempts set submitted_at = now(), score = v_total, max_score = v_max where id = p_attempt;
    if v_mode = 'mock' then
      perform public.ot_record_mock_score(p_attempt);
    end if;
  end if;
  return (
    select jsonb_build_object('score', score, 'max_score', max_score)
           || case when mode = 'mock' then jsonb_build_object('sections', config -> 'sections', 'total', config -> 'total')
                   else '{}'::jsonb end
      from public.ot_attempts where id = p_attempt
  );
end;
$$;

------------------------------------------------------------------ content import (service role only)
-- Taxonomy: {"sections": [{"slug", "name", "sort", "chapters": [{"slug", "name", "sort",
--            "topics": [{"slug", "name", "sort"}]}]}]}
create function public.ot_bank_upsert_taxonomy(p_course text, p_taxonomy jsonb) returns void
language plpgsql security definer set search_path = '' as $$
declare
  s jsonb;
  c jsonb;
  t jsonb;
  v_subject int;
  v_chapter int;
begin
  for s in select value from jsonb_array_elements(p_taxonomy -> 'sections') loop
    insert into public.ot_subjects (course_id, slug, name, sort)
    values (p_course, s ->> 'slug', s ->> 'name', coalesce((s ->> 'sort')::int, 0))
    on conflict (course_id, slug) do update set name = excluded.name, sort = excluded.sort
    returning id into v_subject;
    for c in select value from jsonb_array_elements(s -> 'chapters') loop
      insert into public.ot_chapters (subject_id, slug, name, sort)
      values (v_subject, c ->> 'slug', c ->> 'name', coalesce((c ->> 'sort')::int, 0))
      on conflict (subject_id, slug) do update set name = excluded.name, sort = excluded.sort
      returning id into v_chapter;
      for t in select value from jsonb_array_elements(c -> 'topics') loop
        insert into public.ot_topics (chapter_id, slug, name, sort)
        values (v_chapter, t ->> 'slug', t ->> 'name', coalesce((t ->> 'sort')::int, 0))
        on conflict (chapter_id, slug) do update set name = excluded.name, sort = excluded.sort;
      end loop;
    end loop;
  end loop;
end;
$$;

-- One set: {"id", "section", "chapter", "topic", "pool", "stimulus": {"kind", "title", "html",
--   "audio_script"} | null, "questions": [{"id", "type", "stem_html", "options": [{"label", "html"}],
--   "answer", "explain_html", "tags", "difficulty"}]}
create function public.ot_bank_upsert_set(p_course text, p_source text, p_set jsonb) returns int
language plpgsql security definer set search_path = '' as $$
declare
  v_subject int;
  v_topic int;
  v_source int;
  v_stimulus int;
  v_question int;
  q jsonb;
  n bigint;
  v_n int := 0;
begin
  select s.id, t.id into v_subject, v_topic
    from public.ot_subjects s
    join public.ot_chapters c on c.subject_id = s.id
    join public.ot_topics t on t.chapter_id = c.id
   where s.course_id = p_course and s.slug = p_set ->> 'section'
     and c.slug = p_set ->> 'chapter' and t.slug = p_set ->> 'topic';
  if not found then
    raise exception 'unknown topic %/%/% in %', p_set ->> 'section', p_set ->> 'chapter', p_set ->> 'topic', p_course;
  end if;

  insert into public.ot_sources (course_id, path, subject_id, title)
  values (p_course, p_source, v_subject, p_source)
  on conflict (path) do update set subject_id = excluded.subject_id
  returning id into v_source;

  if jsonb_typeof(p_set -> 'stimulus') = 'object' then
    insert into public.ot_stimuli (ext_id, course_id, kind, title, html, audio_script)
    values (
      p_set ->> 'id', p_course, p_set -> 'stimulus' ->> 'kind',
      coalesce(p_set -> 'stimulus' ->> 'title', ''), coalesce(p_set -> 'stimulus' ->> 'html', ''),
      p_set -> 'stimulus' ->> 'audio_script'
    )
    on conflict (ext_id) do update set
      kind = excluded.kind, title = excluded.title, html = excluded.html, audio_script = excluded.audio_script
    returning id into v_stimulus;
  end if;

  for q, n in select value, ordinality from jsonb_array_elements(p_set -> 'questions') with ordinality loop
    insert into public.ot_questions (
      course_id, ext_id, set_id, topic_id, source_id, number_in_source, type, stem_html,
      difficulty, status, pool, tags, stimulus_id, content_hash
    )
    values (
      p_course, q ->> 'id', p_set ->> 'id', v_topic, v_source, n::int, q ->> 'type', coalesce(q ->> 'stem_html', ''),
      coalesce((q ->> 'difficulty')::int, 2),
      case when q ->> 'type' <> 'essay' and coalesce(jsonb_typeof(q -> 'answer'), 'null') = 'null'
           then 'needs_review' else 'ok' end,
      coalesce(p_set ->> 'pool', 'practice'),
      coalesce((select array_agg(x) from jsonb_array_elements_text(q -> 'tags') x), '{}'),
      v_stimulus,
      md5(p_course || ':' || (q ->> 'id'))
    )
    on conflict (ext_id) do update set
      set_id = excluded.set_id, topic_id = excluded.topic_id, source_id = excluded.source_id,
      number_in_source = excluded.number_in_source, type = excluded.type, stem_html = excluded.stem_html,
      difficulty = excluded.difficulty, status = excluded.status, pool = excluded.pool,
      tags = excluded.tags, stimulus_id = excluded.stimulus_id
    returning id into v_question;

    insert into public.ot_question_keys (question_id, answer_key, answer_source, solution_html)
    values (v_question, q -> 'answer', 'bank', coalesce(q ->> 'explain_html', ''))
    on conflict (question_id) do update set
      answer_key = excluded.answer_key, answer_source = excluded.answer_source, solution_html = excluded.solution_html;

    delete from public.ot_options where question_id = v_question;
    insert into public.ot_options (question_id, label, html, sort)
    select v_question, o ->> 'label', o ->> 'html', (i - 1)::int
      from jsonb_array_elements(coalesce(q -> 'options', '[]')) with ordinality as x (o, i);
    v_n := v_n + 1;
  end loop;
  return v_n;
end;
$$;

-- Mock test: {"id", "title", "minutes", "week", "sections": [{"key", "label", "scale", "sets": [set ids]}]}
create function public.ot_bank_upsert_mock(p_course text, p_mock jsonb) returns int
language plpgsql security definer set search_path = '' as $$
declare
  sec jsonb;
  v_set text;
  v_sort int := 0;
  r record;
begin
  insert into public.ot_mock_tests (id, course_id, title, minutes, week, sections, published, sort)
  values (
    p_mock ->> 'id', p_course, p_mock ->> 'title', (p_mock ->> 'minutes')::int, (p_mock ->> 'week')::int,
    (select jsonb_agg(s - 'sets') from jsonb_array_elements(p_mock -> 'sections') s),
    coalesce((p_mock ->> 'published')::boolean, true), coalesce((p_mock ->> 'sort')::int, 0)
  )
  on conflict (id) do update set
    course_id = excluded.course_id, title = excluded.title, minutes = excluded.minutes, week = excluded.week,
    sections = excluded.sections, published = excluded.published, sort = excluded.sort;

  delete from public.ot_mock_questions where test_id = p_mock ->> 'id';
  for sec in select value from jsonb_array_elements(p_mock -> 'sections') loop
    for v_set in select jsonb_array_elements_text(sec -> 'sets') loop
      for r in
        select id from public.ot_questions
         where set_id = v_set and course_id = p_course and pool = 'mock'
         order by number_in_source
      loop
        insert into public.ot_mock_questions (test_id, question_id, section, sort)
        values (p_mock ->> 'id', r.id, sec ->> 'key', v_sort);
        v_sort := v_sort + 1;
      end loop;
    end loop;
  end loop;
  if v_sort = 0 then
    raise exception 'mock % has no questions; import its sets first', p_mock ->> 'id';
  end if;
  return v_sort;
end;
$$;

