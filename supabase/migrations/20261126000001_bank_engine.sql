create function public.ot_require_course(p_course text) returns void
language plpgsql stable security definer set search_path = '' as $$
begin
  if auth.uid() is null or p_course is null or not (public.is_enrolled(p_course) or public.is_admin()) then
    raise exception 'not enrolled in %', coalesce(p_course, 'this course') using errcode = '42501';
  end if;
end;
$$;

create function public.ot_question_course(p_question int) returns text
language sql stable security definer set search_path = '' as $$
  select course_id from public.ot_questions where id = p_question;
$$;

create function public.ot_topic_course(p_topic int) returns text
language sql stable security definer set search_path = '' as $$
  select s.course_id from public.ot_topics t
    join public.ot_chapters c on c.id = t.chapter_id
    join public.ot_subjects s on s.id = c.subject_id
   where t.id = p_topic;
$$;

