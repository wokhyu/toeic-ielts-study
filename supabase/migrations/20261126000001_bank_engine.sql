create function public.ot_topic_tree(p_course text default 'on-tap-11')
returns table (
  subject_id int, subject_slug text, subject_name text,
  chapter_id int, chapter_name text,
  topic_id int, topic_slug text, topic_name text,
  total bigint, seen bigint, correct bigint
)
language plpgsql stable security definer set search_path = '' as $$
#variable_conflict use_column
begin
  perform public.ot_require_course(p_course);
  return query
  select s.id, s.slug, s.name, c.id, c.name, t.id, t.slug, t.name,
         (select count(*) from public.ot_questions q where q.topic_id = t.id and q.status = 'ok' and q.pool = 'practice'),
         (select count(*) from public.ot_question_stats qs join public.ot_questions q on q.id = qs.question_id
           where qs.user_id = auth.uid() and q.topic_id = t.id and q.pool = 'practice' and qs.seen > 0),
         (select count(*) from public.ot_question_stats qs join public.ot_questions q on q.id = qs.question_id
           where qs.user_id = auth.uid() and q.topic_id = t.id and q.pool = 'practice' and qs.correct > 0)
    from public.ot_subjects s
    join public.ot_chapters c on c.subject_id = s.id
    join public.ot_topics t on t.chapter_id = c.id
   where s.course_id = p_course
   order by s.sort, c.sort, t.sort;
end;
$$;

create or replace function public.ot_topic_question_ids(p_topic int, p_limit int default 20, p_offset int default 0)
returns setof int
language plpgsql stable security definer set search_path = '' as $$
begin
  perform public.ot_require_course(public.ot_topic_course(p_topic));
  return query
  select q.id from public.ot_questions q
    left join public.ot_question_stats qs on qs.question_id = q.id and qs.user_id = auth.uid()
   where q.topic_id = p_topic and q.status = 'ok' and q.pool = 'practice'
   order by coalesce(qs.seen, 0), q.number_in_source, q.id
   limit least(greatest(p_limit, 1), 50) offset greatest(p_offset, 0);
end;
$$;

-- Practice one tag (a grammar point or question type): new questions first,
-- then ones the learner has got wrong, then the rest. Questions sharing a
-- passage stay together.
create function public.ot_tag_question_ids(p_course text, p_tag text, p_limit int default 20)
returns setof int
language plpgsql stable security definer set search_path = '' as $$
begin
  perform public.ot_require_course(p_course);
  return query
  select q.id from public.ot_questions q
    left join public.ot_question_stats qs on qs.question_id = q.id and qs.user_id = auth.uid()
   where q.course_id = p_course and q.status = 'ok' and q.pool = 'practice' and p_tag = any (q.tags)
   order by case when qs.question_id is null then 0 when qs.correct < qs.seen then 1 else 2 end,
            coalesce(q.set_id, ''), q.number_in_source, q.id
   limit least(greatest(p_limit, 1), 50);
end;
$$;

create or replace function public.ot_answer_practice(p_question int, p_response jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_type text;
  v_key jsonb;
  v_solution text;
  g record;
begin
  perform public.ot_require_course(public.ot_question_course(p_question));
  perform public.ot_require_not_in_open_exam(p_question);
  select q.type, k.answer_key, coalesce(k.solution_html, '')
    into v_type, v_key, v_solution
    from public.ot_questions q left join public.ot_question_keys k on k.question_id = q.id
   where q.id = p_question and q.status = 'ok' and q.pool = 'practice';
  if not found then
    raise exception 'question % not found', p_question using errcode = 'P0002';
  end if;
  select * into g from public.ot_grade(v_type, v_key, p_response);
  perform public.ot_bump_stats(auth.uid(), p_question, g.is_correct);
  return jsonb_build_object('score', g.score, 'is_correct', g.is_correct, 'answer_key', v_key, 'solution_html', v_solution);
end;
$$;

create or replace function public.ot_reveal(p_question int) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v jsonb;
begin
  perform public.ot_require_course(public.ot_question_course(p_question));
  perform public.ot_require_not_in_open_exam(p_question);
  if not public.is_admin() and not exists (
    select 1 from public.ot_question_stats where user_id = auth.uid() and question_id = p_question and seen > 0
  ) then
    raise exception 'answer the question first' using errcode = '42501';
  end if;
  select jsonb_build_object('answer_key', k.answer_key, 'solution_html', k.solution_html) into v
    from public.ot_question_keys k where k.question_id = p_question;
  return coalesce(v, jsonb_build_object('answer_key', null, 'solution_html', ''));
end;
$$;

