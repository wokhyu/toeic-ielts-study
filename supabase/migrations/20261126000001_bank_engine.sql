------------------------------------------------------------------ grading
-- Short answers may now list several accepted answers (["colour", "color"]).
-- Numbers are compared as numbers only when the accepted answer is purely
-- numeric, so "15 June" never matches a key of "15 May".
create or replace function public.ot_grade(p_type text, p_key jsonb, p_response jsonb, out score int, out is_correct boolean)
language plpgsql immutable set search_path = '' as $$
declare
  v_picked text;
  v_want text;
  v_given text;
  v_label text;
  v_hits int := 0;
  v_n int := 0;
  a numeric;
  b numeric;
begin
  if p_type = 'essay' or p_key is null or jsonb_typeof(p_key) = 'null' then
    score := null;
    is_correct := null;
    return;
  end if;

  if p_type = 'mcq' then
    v_picked := case when jsonb_typeof(p_response) = 'string' then upper(btrim(p_response #>> '{}')) else '' end;
    v_want := upper(btrim(p_key #>> '{}'));
    is_correct := v_picked <> '' and v_picked = v_want;
    score := case when is_correct then 100 else 0 end;
    return;
  end if;

  if p_type = 'truefalse' then
    for v_label in select jsonb_object_keys(p_key) loop
      v_n := v_n + 1;
      if jsonb_typeof(p_response) = 'object' and p_response ? v_label
         and (p_response -> v_label) = (p_key -> v_label) then
        v_hits := v_hits + 1;
      end if;
    end loop;
    score := case
      when v_n = 4 then (array[0, 10, 25, 50, 100])[v_hits + 1]
      else round(v_hits::numeric / greatest(v_n, 1) * 100)::int
    end;
    is_correct := v_hits = v_n;
    return;
  end if;

  -- short answer
  v_given := case when jsonb_typeof(p_response) = 'string' then btrim(p_response #>> '{}') else '' end;
  is_correct := false;
  if v_given <> '' then
    for v_want in
      select btrim(e #>> '{}')
        from jsonb_array_elements(case when jsonb_typeof(p_key) = 'array' then p_key else jsonb_build_array(p_key) end) e
    loop
      if v_want ~ '^\s*[-+]?[0-9.,]+(\s*/\s*[-+]?[0-9.,]+)?\s*$' then
        a := public.ot_parse_number(v_given);
        b := public.ot_parse_number(v_want);
        is_correct := a is not null and b is not null and abs(a - b) <= 0.000001 * greatest(1, abs(a), abs(b));
      else
        is_correct := lower(regexp_replace(v_given, '\s+', '', 'g')) = lower(regexp_replace(v_want, '\s+', '', 'g'));
      end if;
      exit when is_correct;
    end loop;
  end if;
  score := case when is_correct then 100 else 0 end;
end;
$$;

